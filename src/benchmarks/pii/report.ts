const pct = (value: number, digits = 2) => `${(value * 100).toFixed(digits)}%`;
const ms = (value: number) =>
  value < 1 ? value.toFixed(3) : value < 100 ? value.toFixed(2) : value.toFixed(0);
const int = (value: number) => value.toLocaleString('en-US');

function table(
  headers: string[],
  rows: Array<Array<string | number>>,
  align?: Array<'l' | 'r'>,
): string {
  const marks = headers.map((_, index) =>
    (align?.[index] ?? (index === 0 ? 'l' : 'r')) === 'l' ? ':---' : '---:',
  );
  return [
    `| ${headers.join(' | ')} |`,
    `| ${marks.join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

